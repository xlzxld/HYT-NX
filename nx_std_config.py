# -*- coding: utf-8 -*-
"""
nx_std_config.py —— 标准件默认参数配置文件（用户可自行修改）  v1.29
=====================================================================

【这个文件是干什么的】
    nx_extrude_runner.py 启动时会读取本文件。所有"标准件的默认定位/布尔/
    半径/Z基准/方向/偏移"都集中在本文件的 STD_PART_DEFAULTS 表里，
    你直接改这张表即可：
      * 改某个类型标准件的默认参数   → 找到对应行修改
      * 新增一种标准件               → 在表里加一行（照抄格式）
    改完保存后重开 NX 对话框立即生效，无需动主脚本任何代码。

【改错了会怎样】
    主脚本会对每个字段做合法性检查（sanitize），非法值一律回落到
    安全默认：不会报错、不会崩，但可能不是你想要的行为——改完建议跑一次。

【两个文件的分工】(重要, 请区分)
    ┌─────────────────────────┬──────────────────────────────────────┐
    │ nx_std_config.py        │ 出厂默认值(本文件)。对话框"恢复默认"  │
    │ (你现在看的)            │ 按钮也按这张表恢复。手工编辑。        │
    ├─────────────────────────┼──────────────────────────────────────┤
    │ nx_extrude_params.json  │ 运行记忆(脚本自动写, 一般不要手改)。  │
    │                         │ 存上次的选择/各层拉伸参数/每件改过的  │
    │                         │ 参数/加热条起始结束距离。             │
    └─────────────────────────┴──────────────────────────────────────┘
    记忆优先于出厂默认：你在界面上改过的参数会存进 json，下次打开显示
    的是 json 里的值而不是本表的值。想让某类件回到本表的出厂默认 →
    在界面上点该件的"恢复默认"按钮（或按下述方法清空记忆）。

【如何彻底清空记忆(回到出厂状态)】
    方法一：把 nx_extrude_params.json 删除或改名，下次运行重建全新记忆；
    方法二：把下面的 CONFIG_SCHEMA_VERSION 加 1 —— 脚本将忽略旧记忆中
            的标准件规则(全部回本表默认)，界面参数(分层拉伸数值)也会
            回默认。适合"记忆搞乱了想全部重来"。

【新增一种标准件的操作步骤】
    1. 把 xxx.prt 放进脚本同目录的 stdparts 文件夹;
    2. 在下方 STD_PART_DEFAULTS 表里加一行:
           ("xxx", {"layer": "RZ", "r_min": 0.0, "r_max": 15.0,
                    "z_mode": "FLB_BOTTOM", "bool_mode": "PLACE"}),
       关键词 "xxx" 是文件名包含的字样(不分大小写), 注意别与已有行重复
       ——重复关键词只有第一条命中会生效(自测会报"配置表无重复关键词");
    3. 每个字段怎么填见下表注释; 不写的字段用安全默认
       (layer=""全部图层, r_min=0, r_max=9999 全半径,
        z_mode="FLB_TOP", bool_mode="PLACE", dir="+Z",
        off_x/off_y/off_z=0)。
       注: 早期的独立 "z" 字段已于 v1.13 删除——放置高度只由
       z_mode 选出的基准面 + off_z 决定, 表里再写 z 也不会生效。

【参考点 "ref"——必填, 不填该件不可用(v1.30)】
    放置公式: 图纸定位点 − ref + XYZ偏移。ref =【零件坐标系】里
    零件上的插入基准点(mm), 由你用 NX 测量工具实测后填进表里
    (精确文件名行)。没有 ref 的标准件播放时会跳过并弹提示。
    设计新 prt 时把原点建在插入位置最省事。
"""

